"""`config_ledger.hydra.dump`: ConfigStore nodes -> static YAML that Hydra reloads."""

import sys
import textwrap

import pytest

pytest.importorskip("hydra")
from hydra import compose, initialize, initialize_config_dir  # noqa: E402
from hydra.core.config_store import ConfigStore  # noqa: E402
from omegaconf import OmegaConf  # noqa: E402

from config_ledger.cli import main  # noqa: E402
from config_ledger.hydra.dump import (  # noqa: E402
    CREATED,
    UNCHANGED,
    UPDATED,
    capture_registrations,
    dump_config_store,
)
from tests.conftest import Method, MiningGoldTrainer, Trainer  # noqa: E402


def register():
    cs = ConfigStore.instance()
    cs.store(name="app", node={"defaults": [{"method": "default"}, "_self_"],
                               "lr": "${method.trainer.learning_rate}", "data_path": "???"})
    cs.store(group="method", name="default", node=Method)
    cs.store("gold", MiningGoldTrainer, "method/trainer")  # positional, nested group
    cs.store(group="method/trainer", name="slow.yaml", node=Trainer(learning_rate=0.01))
    cs.store(group="extras", name="tag", node={"label": "x"}, package="meta.tags")


ENTRIES = [(None, "app"), ("method", "default"), ("method/trainer", "gold"),
           ("method/trainer", "slow"), ("extras", "tag")]


@pytest.fixture
def store():
    """The ConfigStore, with this module's entries removed afterwards (it is a process-wide
    singleton; Hydra registers its own plugin nodes into it lazily, so it is not snapshotted)."""
    cs = ConfigStore.instance()
    yield cs
    for key in ("app.yaml", "method", "extras"):
        cs.repo.pop(key, None)


def _compose(overrides, config_dir=None):
    if config_dir is None:
        with initialize(version_base=None):
            cfg = compose("app", overrides)
    else:
        with initialize_config_dir(config_dir=str(config_dir), version_base=None):
            cfg = compose("app", overrides)
    return OmegaConf.to_container(cfg)


def test_capture_registrations_returns_entries_in_order(store):
    assert capture_registrations(register) == ENTRIES
    assert "store" not in vars(store)  # the wrapper is gone
    assert store.load("method/trainer/gold.yaml").node.alpha == 0.5  # stored as usual


@pytest.mark.parametrize("overrides", [[], ["+method/trainer=gold"], ["+method/trainer=slow"],
                                       ["+extras=tag", "data_path=/d"]])
def test_dump_round_trips_through_hydra(store, tmp_path, overrides):
    entries = capture_registrations(register)
    from_store = _compose(overrides)
    dump_config_store(entries, tmp_path)
    for group, name in entries:  # compose from the files alone
        parent = store.repo
        for part in (group.split("/") if group else []):
            parent = parent[part]
        del parent[f"{name}.yaml"]
    assert _compose(overrides, tmp_path) == from_store


def test_dumped_yaml_layout_and_content(store, tmp_path):
    dump_config_store(capture_registrations(register), tmp_path)
    gold = (tmp_path / "method" / "trainer" / "gold.yaml").read_text()
    assert gold.startswith("# Generated by config-ledger dump-configs from ConfigStore entry "
                           "method/trainer/gold; do not edit.\n")
    assert f"_target_: {MiningGoldTrainer._target_}" in gold
    assert "VERSION" not in gold and "config_version" not in gold
    app = (tmp_path / "app.yaml").read_text()
    assert "lr: ${method.trainer.learning_rate}" in app and "data_path: ???" in app
    tag = (tmp_path / "extras" / "tag.yaml").read_text().splitlines()
    assert tag[0] == "# @package meta.tags"  # Hydra reads `# @` lines only before any other


def test_statuses_check_mode_and_other_files(store, tmp_path):
    entries = capture_registrations(register)
    hand_written = tmp_path / "method" / "custom.yaml"
    hand_written.parent.mkdir()
    hand_written.write_text("name: mine\n")

    checked = dump_config_store(entries, tmp_path, check=True)
    assert {d.status for d in checked} == {CREATED}
    assert sorted(p.name for p in tmp_path.rglob("*.yaml")) == ["custom.yaml"]  # nothing written

    assert {d.status for d in dump_config_store(entries, tmp_path)} == {CREATED}
    assert {d.status for d in dump_config_store(entries, tmp_path, check=True)} == {UNCHANGED}

    store.store(group="method", name="default", node=Method(name="renamed"))
    statuses = {(d.group, d.name): d.status for d in dump_config_store(entries, tmp_path)}
    assert statuses[("method", "default")] == UPDATED
    assert "name: renamed" in (tmp_path / "method" / "default.yaml").read_text()
    assert hand_written.read_text() == "name: mine\n"


SETUP = textwrap.dedent("""\
    from hydra.core.config_store import ConfigStore

    LABEL = "x"

    def register():
        cs = ConfigStore.instance()
        cs.store(group="method", name="default", node={"name": LABEL})
        cs.store(name="app", node={"defaults": [{"method": "default"}, "_self_"]})
    """)


@pytest.fixture
def setup_module(tmp_path, monkeypatch, store):
    (tmp_path / "dump_setup.py").write_text(SETUP)
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(sys, "path", list(sys.path))
    sys.modules.pop("dump_setup", None)
    yield sys.modules
    sys.modules.pop("dump_setup", None)


def test_cli_dump_and_check(setup_module, tmp_path, capsys):
    args = ["dump-configs", "--setup", "dump_setup:register", "--out", "conf"]
    assert main([*args, "--check"]) == 1
    assert "would be created" in capsys.readouterr().out
    assert not (tmp_path / "conf").exists()

    assert main(args) == 0
    assert (tmp_path / "conf" / "app.yaml").exists()
    assert "name: x" in (tmp_path / "conf" / "method" / "default.yaml").read_text()
    assert main([*args, "--check"]) == 0
    assert "2 of 2 file(s) already current" in capsys.readouterr().out

    setup_module["dump_setup"].LABEL = "y"  # a changed default, not yet regenerated
    assert main([*args, "--check"]) == 1
    assert "would be updated: conf/method/default.yaml" in capsys.readouterr().out


def test_cli_errors(setup_module, capsys):
    assert main(["dump-configs", "--setup", "dump_setup", "--out", "conf"]) == 2  # no FUNC
    assert "registered no ConfigStore entries" in capsys.readouterr().err
    assert main(["dump-configs", "--setup", "no_such_module:f", "--out", "conf"]) == 2
    assert "ModuleNotFoundError" in capsys.readouterr().err
