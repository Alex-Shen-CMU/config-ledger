"""Dump ``ConfigStore`` nodes to a tree of static YAML.

Apps that define their configs as dataclasses and register them with ``cs.store(...)`` often
also keep static YAML copies under the config directory, so the defaults are readable and
editable without Python. This module regenerates those copies::

    from config_ledger.hydra.dump import capture_registrations, dump_config_store

    dump_config_store(capture_registrations(my_app.register_configs), "conf")

Each ``(group, name)`` entry is read back from ``ConfigStore.instance()`` and written to
``<out_dir>/<group>/<name>.yaml`` as ``OmegaConf.to_yaml`` of its node: interpolations and
``???`` stay unresolved, ``_target_`` is kept, and a non-default ``package`` becomes a
``# @package`` header line, so composing ``group=name`` from the dumped directory gives the same
config as composing it from the ``ConfigStore``. A ``VersionedConfig``'s ``VERSION`` is a class
variable and is not written; it is always resolved from the live class.

Only the listed entries are written. Other files under ``out_dir`` (hand-written YAML next to
the generated ones) are never touched, and nothing is deleted. Which entries to dump is the
caller's choice: the ``ConfigStore`` also holds Hydra's own ``hydra/*`` nodes and plugin schemas.

``check=True`` writes nothing and reports which files are missing or out of date, for CI.
CLI: ``config-ledger dump-configs``.

Status (2026-10-18): introduced, the generic half of an internal project's config
generation script; the project's registration list stays in the project.
"""

from __future__ import annotations

import inspect
import os
from collections.abc import Callable, Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from hydra.core.config_store import ConfigStore
from omegaconf import OmegaConf

HEADER = "# Generated by config-ledger dump-configs from ConfigStore entry {entry}; do not edit."

CREATED = "created"
UPDATED = "updated"
UNCHANGED = "unchanged"


@dataclass(frozen=True)
class DumpedFile:
    """One entry's YAML file and whether it was (with ``check``: would be) created or updated."""

    group: str | None
    name: str
    path: Path
    status: str  # CREATED | UPDATED | UNCHANGED


def capture_registrations(register: Callable[[], Any]) -> list[tuple[str | None, str]]:
    """Call ``register()`` and return the ``(group, name)`` of every ``ConfigStore.store`` call
    it made, in order and without duplicates. The nodes are stored as usual."""
    cs = ConfigStore.instance()
    original = cs.store
    shadowed = "store" in vars(cs)  # already wrapped, e.g. by an enclosing capture
    signature = inspect.signature(original)
    captured: dict[tuple[str | None, str], None] = {}

    def capturing_store(*args: Any, **kwargs: Any) -> None:
        bound = signature.bind(*args, **kwargs)
        group = bound.arguments.get("group") or None
        captured[(group, _strip_yaml(bound.arguments["name"]))] = None
        original(*args, **kwargs)

    cs.store = capturing_store  # type: ignore[method-assign]
    try:
        register()
    finally:
        if shadowed:
            cs.store = original  # type: ignore[method-assign]
        else:
            del cs.store  # the class method shows through again
    return list(captured)


def render_entry(group: str | None, name: str) -> str:
    """The YAML text written for one ``ConfigStore`` entry, header included."""
    name = _strip_yaml(name)
    entry = f"{group}/{name}" if group else name
    node = ConfigStore.instance().load(f"{entry}.yaml")
    header = [HEADER.format(entry=entry)]
    if node.package:
        # First: Hydra stops reading `# @` directives at the first other line.
        header.insert(0, f"# @package {node.package}")
    return "\n".join(header) + "\n" + OmegaConf.to_yaml(node.node)


def dump_config_store(
    entries: Iterable[tuple[str | None, str]],
    out_dir: str | os.PathLike[str],
    *,
    check: bool = False,
) -> list[DumpedFile]:
    """Write each ``(group, name)`` entry of the ``ConfigStore`` to
    ``<out_dir>/<group>/<name>.yaml`` (``group`` ``None`` or ``""``: ``<out_dir>/<name>.yaml``).

    Files whose content is already current are left as they are. With ``check``, nothing is
    written; the returned statuses say what a dump would do.
    """
    out_dir = Path(out_dir)
    results = []
    for group, name in entries:
        name = _strip_yaml(name)
        text = render_entry(group, name)
        path = (out_dir / group if group else out_dir) / f"{name}.yaml"
        if not path.exists():
            status = CREATED
        elif path.read_text() != text:
            status = UPDATED
        else:
            status = UNCHANGED
        if status != UNCHANGED and not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        results.append(DumpedFile(group or None, name, path, status))
    return results


def _strip_yaml(name: str) -> str:
    return name[: -len(".yaml")] if name.endswith(".yaml") else name
